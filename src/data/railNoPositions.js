let decoded = null;
/** The rings as [[lon, lat], ...] with their boxes, decoded once. */
function rings() {
  if (decoded) return decoded;
  const scale = 10 ** DECIMALS;
  decoded = RINGS.map((encoded) => {
    const ring = [];
    let lon = 0;
    let lat = 0;
    for (let i = 0; i + 1 < encoded.length; i += 2) {
      lon += encoded[i];
      lat += encoded[i + 1];
      ring.push([lon / scale, lat / scale]);
    }
    const box = ring.reduce(
      (b, [x, y]) => ({
        west: Math.min(b.west, x),
        east: Math.max(b.east, x),
        south: Math.min(b.south, y),
        north: Math.max(b.north, y),
      }),
      { west: Infinity, east: -Infinity, south: Infinity, north: -Infinity },
    );
    return { ring, box };
  });
  return decoded;
}

/** Every ring's box together: the cheap first test. */
export const NO_TRAIN_POSITION_BOX = Object.freeze(
  rings().reduce(
    (b, { box }) => ({
      west: Math.min(b.west, box.west),
      east: Math.max(b.east, box.east),
      south: Math.min(b.south, box.south),
      north: Math.max(b.north, box.north),
    }),
    { west: Infinity, east: -Infinity, south: Infinity, north: -Infinity },
  ),
);

function inRing(ring, lat, lon) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    )
      inside = !inside;
  }
  return inside;
}

/**
 * Whether a position lies where no train may be placed.
 * @param {number} lat
 * @param {number} lon
 * @returns {boolean}
 */
export function isNoTrainPositionPoint(lat, lon) {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return false;
  const all = NO_TRAIN_POSITION_BOX;
  if (lat < all.south || lat > all.north || lon < all.west || lon > all.east)
    return false;
  return rings().some(
    ({ ring, box }) =>
      lat >= box.south &&
      lat <= box.north &&
      lon >= box.west &&
      lon <= box.east &&
      inRing(ring, lat, lon),
  );
}

/**
 * The country a stop id names, for ids that start with one (IFOPT-style
 * `ua:22005:1:1`, parent stations `Pua:22005`), as an upper-case ISO code;
 * else null.
 * @param {string|null|undefined} stopId
 * @returns {string|null}
 */
export function stopIdCountry(stopId) {
  return (
    /^P?([a-z]{2}):\d/i.exec(String(stopId ?? ''))?.[1]?.toUpperCase() ?? null
  );
}

/**
 * Whether a stop lies where no train may be placed: when the country its id
 * names is one of them, or when its position is inside the outline. Either
 * is enough, so a stop is never kept on its id's word alone: a stop whose id
 * names another country but whose coordinates are in Ukraine is left out
 * too.
 * @param {{id?: string, lat?: number, lon?: number}|null|undefined} stop
 * @returns {boolean}
 */
export function isNoTrainPositionStop(stop) {
  if (!stop) return false;
  const country = stopIdCountry(stop.id);
  if (country && NO_TRAIN_POSITION_COUNTRIES.includes(country)) return true;
  return isNoTrainPositionPoint(Number(stop.lat), Number(stop.lon));
}
