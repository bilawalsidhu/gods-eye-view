import { readFile, writeFile, mkdir } from 'node:fs/promises';
import {
  cardFromEntity,
  validateDiscoveryPack,
} from '../src/discovery/model.js';

export const DISCOVERY_SELECTION = Object.freeze([
  ['Q243', 'landmark', 'earth', ['Eiffel', 'Tour Eiffel']],
  ['Q10285', 'landmark', 'earth', ['Colosseum', 'Colisée']],
  ['Q9141', 'landmark', 'earth', ['Taj Mahal']],
  ['Q39671', 'landmark', 'earth', ['Stonehenge']],
  ['Q37200', 'landmark', 'earth', ['Great Pyramid', 'Pyramide de Khéops']],
  ['Q676203', 'landmark', 'earth', ['Machu Picchu']],
  ['Q118841', 'landform', 'earth', ['Grand Canyon']],
  ['Q5788', 'landmark', 'earth', ['Petra', 'Pétra']],
  ['Q9202', 'landmark', 'earth', ['Statue of Liberty', 'Statue de la Liberté']],
  [
    'Q6475',
    'vehicle-type',
    'earth',
    ['A320', 'A319', 'A318', 'A321', 'A20N', 'A21N'],
  ],
  [
    'Q6387',
    'vehicle-type',
    'earth',
    ['B737', 'B738', 'B739', 'B38M', 'B39M', 'Boeing 737'],
  ],
  ['Q520', 'planetary-feature', 'mars', ['Olympus Mons']],
  ['Q621110', 'planetary-feature', 'mars', ['Valles Marineris']],
  ['Q631696', 'planetary-feature', 'moon', ['Tycho crater', 'Cratère Tycho']],
  [
    'Q732758',
    'mission-site',
    'moon',
    ['Tranquility Base', 'Base de la Tranquillité'],
  ],
]);
const input = process.argv[2];
if (!input)
  throw new Error(
    'Usage: node scripts/build-discovery-pack.mjs <wbgetentities-json> [snapshot-date]',
  );
const retrievedAt = process.argv[3] ?? new Date().toISOString().slice(0, 10);
const data = JSON.parse(await readFile(input, 'utf8'));
const cards = DISCOVERY_SELECTION.map(([id, kind, body, aliases]) => {
  const card = cardFromEntity(data.entities?.[id], {
    kind,
    body,
    aliases,
    retrievedAt,
  });
  if (!card || card.provenance.revision === null)
    throw new Error(`Missing/rejected source entity ${id}`);
  return card;
});
const pack = validateDiscoveryPack({
  format: 'gods-eye-view/discovery-pack',
  version: 1,
  title: 'Discovery starter: Earth, Moon and Mars',
  license: 'CC0-1.0',
  selection:
    'A small editorial sample of nine Earth places, two aircraft families and four Moon/Mars sites. Not a global ranking or complete atlas.',
  cards,
});
await mkdir('src/discovery', { recursive: true });
await writeFile(
  'src/discovery/starterPack.js',
  `// CC0 Wikidata snapshot; generated by scripts/build-discovery-pack.mjs.\nexport const starterPack = ${JSON.stringify(pack, null, 2)};\n`,
);
console.log(
  `Generated ${cards.length} source-linked cards; no Wikipedia prose or external image bytes.`,
);
